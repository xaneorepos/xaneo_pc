  String text(String key, {Map<String, Object> params = const {}}) {
    final fallback = (_locales[_languageCode] ?? _en)[key] ?? _en[key] ?? key;
    final runtime = RuntimeTranslations.instance;
    var value = runtime.containsKey(key)
        ? runtime.get(key, fallback: fallback)
        : fallback;
    for (final entry in params.entries) {
      value = value.replaceAll('{${entry.key}}', entry.value.toString());
    }
    return value;
  }

  String duration(int seconds) {
    if (seconds >= 3600 && seconds % 3600 == 0) {
      return '${seconds ~/ 3600} ${text('messenger.time.hourShort')}';
    }
    if (seconds >= 60 && seconds % 60 == 0) {
      return '${seconds ~/ 60} ${text('messenger.time.minuteShort')}';
    }
    return '$seconds ${text('messenger.time.secondShort')}';
  }
