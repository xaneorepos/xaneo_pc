  /// Resolves the localized text for [key].
  /// First checks runtime custom language pack, then falls back to current
  /// system locale or Russian/English defaults. Also interpolates [params].
  String text(String key, {Map<String, Object> params = const {}}) {
    final fallback = (_locales[_languageCode] ?? _en)[key] ?? _ru[key] ?? key;
    final runtime = RuntimeTranslations.instance;

    String value;
    if (runtime.hasActiveCustomPack) {
      if (runtime.containsKey(key)) {
        value = runtime.get(key, fallback: fallback);
      } else {
        // Reverse-lookup fallback Russian text in case user pack provides translation by text
        final ruFallback = _ru[key] ?? fallback;
        value = runtime.resolveByText(ruFallback);
      }
    } else {
      value = fallback;
    }

    if (params.isNotEmpty) {
      for (final entry in params.entries) {
        value = value.replaceAll('{${entry.key}}', entry.value.toString());
      }
    }
    return value;
  }
